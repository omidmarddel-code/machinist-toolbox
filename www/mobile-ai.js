  // ارقام فارسی/عربی به لاتین؛ کاربر ممکن است «م۱۰×۱/۵» بنویسد
  function toAsciiDigits(s) {
    return String(s == null ? '' : s)
      .replace(/[\u06F0-\u06F9]/g, function (c) { return String(c.charCodeAt(0) - 0x06F0 + 48); })
      .replace(/[\u0660-\u0669]/g, function (c) { return String(c.charCodeAt(0) - 0x0660 + 48); })
      .replace(/[\u066B]/g, '.').replace(/[\u066C]/g, ',');
  }
  // یکسان‌سازی کامل متن پرسش (نرمال فارسی + ارقام + نمادهای ضریب)
  function normQ(s) {
    return normFa(toAsciiDigits(s)).replace(/×/g, 'x').replace(/\s*x\s*/g, 'x');
  }
  // نرمال‌سازی امن برای بیرون‌کشیدن عدد: ممیز و نقطه حفظ می‌شوند
  function numQ(s) {
    return toAsciiDigits(String(s == null ? '' : s))
      .toLowerCase()
      .replace(/[\u064A]/g, 'ی').replace(/[\u0643]/g, 'ک')
      .replace(/[\u200c]/g, ' ')
      .replace(/[×]/g, 'x')
      .replace(/م\s*(?=[\d.])/g, 'm')   // «م۱۰» فارسی → m10
      .replace(/[٫]/g, '.')
      .replace(/\s*x\s*/g, 'x')
      .replace(/\s+/g, ' ')
      .trim();
  }
  function num(v) {
    var s = String(v == null ? '' : v).replace(/[\/٫،]/g, '.').replace(/[^\d.\-]/g, '').replace(/(\..*)\./g, '$1');
    var n = parseFloat(s);
    return isNaN(n) ? null : n;
  }
  // عدد را با d رقم اعشار و بدون صفرهای اضافه می‌نویسد
  function fx(v, d) {
    if (v == null || isNaN(v)) return '—';
    var p = Math.pow(10, d == null ? 2 : d);
    return String(Math.round(v * p) / p);
  }
  function numbersIn(t) {
    var m = String(t || '').match(/\d+(?:\.\d+)?/g) || [];
    var out = [], seen = {};
    for (var i = 0; i < m.length; i++) { if (!seen[m[i]] && out.length < 8) { seen[m[i]] = 1; out.push(m[i]); } }
    return out;
  }
  function hasAny(t, list) {
    for (var i = 0; i < list.length; i++) { if (t.indexOf(normFa(list[i])) !== -1) return list[i]; }
    return '';
  }
