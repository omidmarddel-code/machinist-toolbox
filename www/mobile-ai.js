  // خروجی: { dia, pitch, explicit } یا null. pitch از جدول گام درشت می‌آید.
  function threadSpec(raw) {
    var n = numQ(raw), kw = normQ(raw);
    var threadish = /رزوه|رزه|قلاویز|پیچ|مهره|thread|tap/.test(kw);
    var m = /(?:^|[^\d.])m\s?(\d{1,2}(?:[.\/]\d{1,2})?)\s*x\s*(\d+(?:[.\/]\d{1,2})?)/.exec(n);
    var dia = null, pitch = null, explicit = false;
    if (m) { dia = num(m[1]); pitch = num(m[2]); explicit = true; }
    if (dia == null) {
      m = /(?:^|[^\d.])m\s?(\d{1,2}(?:[.\/]\d{1,2})?)(?![a-z0-9])/i.exec(n);
      if (m && threadish) dia = num(m[1]);
    }
    if (dia == null && threadish) {
      m = /(?:رزوه|رزه|قلاویز)\s*(?:م)?\s*(\d{1,2}(?:[.\/]\d{1,2})?)/.exec(n);
      if (m) dia = num(m[1]);
    }
    if (dia == null || dia < 2 || dia > 64) return null;
    if (pitch == null) {
      pitch = METRIC_PITCH[fx(dia, 2)] == null ? null : METRIC_PITCH[fx(dia, 2)];
      if (!explicit && pitch == null && !threadish) return null;
    }
    if (pitch != null && (pitch < 0.2 || pitch > 8 || pitch > dia)) return null;
    return { dia: dia, pitch: pitch, explicit: explicit };
  }

